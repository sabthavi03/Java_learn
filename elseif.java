

public class elseif {
    public static void main(String args[])
    {
       
       int score = 65;

       if(score >= 35)
       {
        System.out.println("I'll buy you a story book");
       }
       else if(score >= 60)
       {
        System.out.println("I'll buy you a nintendo");
       }

       else if(score >= 75)
       {
        System.out.println("I'll buy you an iPhone");
       }

    }
    
}
